            'אל תחליף מוצר ספציפי בשם כללי יותר רק כדי לקצר אותו, ואל תמציא ניסוח סמנטי חדש; קיצור מותר רק כאשר המילים שהוסרו הן באמת רעש או מידע מובן מאליו. '
